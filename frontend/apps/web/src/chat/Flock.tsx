// The cloud is drawn at the design's width (246px), the sphere at the box's height (115px): the viewBox is 100 units
// tall and as wide as the box, and the cloud is spread around the centre to fill it.
const VIEW_W = 214;
const CLOUD_SPREAD = 2.2;
const R = 1.3;

/** Each cloud dot paired with a sphere dot at about the same angle from the centre, so the flock gathers smoothly. */
const PATHS = (() => {
  const angle = ([x, y]: Dot) => Math.atan2(y - 50, x - 50);
  const cloud = [...CLOUD].sort((a, b) => angle(a) - angle(b));
  const sphere = [...SPHERE].sort((a, b) => angle(a) - angle(b));
  return cloud.map(([x, y, opacity], i) => {
    const [sx, sy] = sphere[Math.floor((i * sphere.length) / cloud.length)];
    return {
      from: [50 + (x - 50) * CLOUD_SPREAD, 50 + (y - 50) * CLOUD_SPREAD],
      to: [sx, sy],
      opacity,
      phase: (i * 2.399) % (2 * Math.PI), // golden angle: neighbours drift out of step
    };
  });
})();

// One loop, cloud -> sphere -> cloud, in seconds. It never holds still: the blend only slows near each shape.
const CYCLE = 9;
// Where the loop starts: already on its way out of the cloud, so the flock is moving from the first frame.
const START = 1.2;
const DRIFT = 1.4; // units each dot wanders around its place

/** 0 = cloud, 1 = sphere, at time t seconds. */
export function blend(t: number): number {
  return (1 - Math.cos((2 * Math.PI * t) / CYCLE)) / 2;
}

/** Where dot i is at time t seconds. */
function position(i: number, t: number): [number, number] {
  const { from, to, phase } = PATHS[i];
  const k = blend(t);
  return [
    from[0] + (to[0] - from[0]) * k + Math.sin(t * 1.1 + phase) * DRIFT,
    from[1] + (to[1] - from[1]) * k + Math.cos(t * 0.8 + phase * 1.3) * DRIFT,
  ];
}

// Listening (Figma "AI / Orb", State=Listening): the flock spreads into a ring that slowly turns.
const RING_R = 42;
const RING_SPIN = 0.15; // radians per second
const RING_EASE = 4; // how fast the flock moves between the ring and the murmuration, per second

/** Where dot i sits on the listening ring at time t seconds. */
function ringPosition(i: number, t: number): [number, number] {
  const { phase } = PATHS[i];
  const a = (i / PATHS.length) * 2 * Math.PI + t * RING_SPIN;
  const r = RING_R + Math.sin(phase * 3) * 3.5 + Math.sin(t * 1.3 + phase) * 0.8;
  return [50 + Math.cos(a) * r, 50 + Math.sin(a) * r];
}

const reducedMotion = () => window.matchMedia?.("(prefers-reduced-motion: reduce)").matches ?? false;

/**
 * Alfred's murmuration (Figma "AI / Orb · Flock"), above the homepage greeting. The flock drifts and keeps
 * gathering into a sphere and scattering back into a cloud; it stays a still cloud when the member prefers reduced
 * motion. With `listening` it spreads into a turning ring (a still ring for reduced motion). Positions are set on
 * the circles directly each frame, so React does not re-render.
 */
export function Flock({ className, listening = false }: { className?: string; listening?: boolean }) {
  const dots = useRef<(SVGCircleElement | null)[]>([]);
  const listeningRef = useRef(listening);
  listeningRef.current = listening;

  const setDot = (i: number, [x, y]: [number, number]) => {
    dots.current[i]?.setAttribute("cx", x.toFixed(2));
    dots.current[i]?.setAttribute("cy", y.toFixed(2));
  };

  // Reduced motion: no animation, just the still cloud or the still ring.
  useEffect(() => {
    if (!reducedMotion()) return;
    PATHS.forEach((_, i) => setDot(i, listening ? ringPosition(i, 0) : position(i, START)));
  }, [listening]);

  useEffect(() => {
    if (reducedMotion() || typeof requestAnimationFrame !== "function") return;
    let frame = 0;
    let ring = listeningRef.current ? 1 : 0; // 0 = murmuration, 1 = ring
    const start = performance.now();
    let last = start;
    const draw = (now: number) => {
      const t = START + (now - start) / 1000;
      const goal = listeningRef.current ? 1 : 0;
      ring += (goal - ring) * Math.min(1, ((now - last) / 1000) * RING_EASE);
      last = now;
      PATHS.forEach((_, i) => {
        const [mx, my] = position(i, t);
        if (ring < 0.001) return setDot(i, [mx, my]);
        const [rx, ry] = ringPosition(i, t);
        setDot(i, [mx + (rx - mx) * ring, my + (ry - my) * ring]);
      });
      frame = requestAnimationFrame(draw);
    };
    frame = requestAnimationFrame(draw);
    return () => cancelAnimationFrame(frame);
  }, []);

  return (
    <svg
      aria-hidden
      viewBox={`${50 - VIEW_W / 2} 0 ${VIEW_W} 100`}
      className={cn("text-flock", className)}
      fill="currentColor"
    >
      {PATHS.map(({ opacity }, i) => (
        <circle
          key={i}
          ref={(el) => {
            dots.current[i] = el;
          }}
          cx={position(i, START)[0]}
          cy={position(i, START)[1]}
          r={R}
          fillOpacity={opacity}
        />
      ))}
    </svg>
  );
}
